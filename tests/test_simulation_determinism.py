"""SIM-02: a run is reproducible and the seed is a live handle (Phase 4, 04-05).

The reproducibility contract has two halves and both are pinned here:

* **The engine is deterministic for a given seed.** Two runs with the same
  seed produce byte-identical aggregates — the same distribution, not merely
  the same shape.
* **The seed is LIVE, not decorative.** Different seeds must not collapse onto
  one distribution, otherwise "reproduce with this seed" would be a promise
  the engine cannot keep.
* **Every run response DECLARES its seed.** The service is the one place a
  run response is shaped, so the ack (and the terminal result) carry
  ``seed``, ``n_simulations`` and ``provenance == "simulated"`` — including
  when the caller omitted the seed and the server generated one (D-11).
"""

from __future__ import annotations

import threading
from typing import Any, Optional

from football_core.domain import ResultProvenance
from football_core.simulation import (
    MonteCarloEngine,
    RunContext,
    SimulationRequest,
    SimulationResult,
    ValueCounter,
)
from web.simulation_service import SimulationTaskService

#: Iterations per run — enough for a coin flip to produce a stable count.
_N = 200


class _CoinRules:
    """A minimal in-test ``SimulationRules``: one coin flip per run.

    It implements the whole protocol the engine needs
    (``declare_aggregations`` / ``simulate_one`` / ``provenance_attestation``)
    so the test exercises the REAL engine, not a stub of it.
    """

    def declare_aggregations(self):
        return {"champion": lambda: ValueCounter("champion")}

    def simulate_one(self, context: RunContext):
        return {"champion": "A" if context.rng.random() < 0.5 else "B"}

    def provenance_attestation(self):
        return {}


def _run(seed: Optional[int]) -> SimulationResult:
    """One engine run with *seed* (an omitted seed is generated by the engine)."""
    return MonteCarloEngine().run(
        SimulationRequest(competition_id="t", season="s", n_simulations=_N,
                          seed=seed),
        _CoinRules(),
    )


def _start(seed: Any) -> tuple[int, dict]:
    """Start one run through the shared service with a stub runner."""
    service = SimulationTaskService()

    def _runner(progress_cb: Any, count: int, run_seed: Optional[int]) -> dict:
        return {"count": count, "seed": run_seed}

    def _on_result(result: dict, count: int, run_seed: Optional[int]) -> dict:
        return {"count": count, "seed": run_seed}

    return service.start(
        competition_id="ucl",
        raw_count=_N,
        default_count=_N,
        seed=seed,
        runner=_runner,
        eligibility_fn=lambda: (True, None, ""),
        on_result=_on_result,
    )


class TestEngineDeterminism:
    """SIM-02: the same seed reproduces the same distribution."""

    def test_same_seed_reproduces_distribution(self):
        """Two runs with the same seed produce byte-identical aggregates."""
        a = _run(12345)
        b = _run(12345)

        assert a.aggregates["champion"] == b.aggregates["champion"]
        assert a.aggregates == b.aggregates
        assert a.metadata.seed == 12345
        assert b.metadata.seed == 12345
        assert a.aggregates["n_simulations"] == _N
        assert a.metadata.provenance == ResultProvenance.SIMULATED.value
        assert a.is_simulated is True

    def test_metadata_declares_the_run_contract(self):
        """The metadata is the run's declaration: count, seed and provenance."""
        result = _run(7)

        assert result.metadata.n_simulations == _N
        assert result.metadata.seed == 7
        assert result.metadata.provenance == ResultProvenance.SIMULATED.value
        assert result.metadata.provenance == "simulated"

    def test_omitted_seed_is_generated_by_the_engine(self):
        """An omitted seed still yields a concrete, usable seed."""
        result = _run(None)

        assert isinstance(result.metadata.seed, int)
        assert result.metadata.seed >= 0
        assert result.aggregates["seed"] == result.metadata.seed

    def test_seed_is_live(self):
        """Different seeds must NOT collapse onto one distribution."""
        counts = {_run(s).aggregates["champion"]["counts"].get("A")
                  for s in range(8)}
        assert len(counts) > 1, counts


class TestRunResponseDeclaresTheSeed:
    """SIM-02 / D-11: the run response carries seed, count and provenance."""

    def test_run_response_carries_seed_n_simulations_provenance(self):
        """An omitted seed is generated server-side and returned."""
        status, ack = _start(None)

        assert status == 200, ack
        assert isinstance(ack["seed"], int), ack
        assert ack["seed"] >= 0, ack
        assert ack["n_simulations"] == _N, ack
        assert ack["provenance"] == ResultProvenance.SIMULATED.value, ack
        assert ack["provenance"] == "simulated"

    def test_explicit_seed_is_echoed(self):
        """An explicit seed is echoed verbatim."""
        status, ack = _start(4242)

        assert status == 200, ack
        assert ack["seed"] == 4242, ack
        assert ack["n_simulations"] == _N, ack
        assert ack["provenance"] == "simulated", ack

    def test_running_poll_response_declares_the_run_contract(self):
        """The POLL response is a run response too — it declares the contract
        from the very first poll, not only once the run has finished.

        A client polls while the run is still executing; if the poll carried
        no seed, the client could not show (or copy) the reproducibility
        handle until the run was over, and the terminal entry is cleaned up
        after a single poll.
        """
        gate = threading.Event()
        service = SimulationTaskService()

        def _runner(progress_cb: Any, count: int, run_seed: Optional[int]) -> dict:
            gate.wait(timeout=10)
            return {}

        status, ack = service.start(
            competition_id="ucl",
            raw_count=_N,
            default_count=_N,
            seed=909,
            runner=_runner,
            eligibility_fn=lambda: (True, None, ""),
            on_result=lambda result, count, run_seed: {},
        )
        try:
            assert status == 200, ack
            payload = service.poll(ack["task_id"])
            assert payload["status"] == "running", payload
            assert payload["seed"] == 909, payload
            assert payload["n_simulations"] == _N, payload
            assert payload["provenance"] == "simulated", payload
        finally:
            gate.set()


class TestServiceSeedReachesTheEngine:
    """D-14: the seed the service hands out is the seed the run uses."""

    def test_service_bound_seed_reaches_the_runner(self):
        received: list[tuple[int, Optional[int]]] = []
        done = threading.Event()
        service = SimulationTaskService()

        def _runner(progress_cb: Any, count: int, run_seed: Optional[int]) -> dict:
            received.append((count, run_seed))
            done.set()
            return {}

        status, ack = service.start(
            competition_id="ucl",
            raw_count=_N,
            default_count=_N,
            seed=31337,
            runner=_runner,
            eligibility_fn=lambda: (True, None, ""),
            on_result=lambda result, count, run_seed: {},
        )
        assert status == 200, ack
        assert done.wait(timeout=10)

        assert received == [(_N, 31337)], received
        assert ack["seed"] == received[0][1]
